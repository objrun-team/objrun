#!/usr/bin/env bash
# Prepare this example's dependencies. **Idempotent**; safe to rerun.
#
#   On Sherlock, request a compute node with `sdev` or `sh_dev`, then run:
#   bash /scratch/users/ehz0002/TgEngin/examples/benchmark/chemiq/setup.sh
#
# **Do not run on a login node**: this installs packages and executes Python self-tests. The engine may run elsewhere; it only knows two URLs.
#
# ## Install the corpus and grader **on the grader side**, outside the repository
#
# Every `questions/chemiq.jsonl` row contains `answer`. A solver could find a repository copy with one glob.
# Vendor the official repository under `$HOME/.cache/tgengin-chemiq/` (override with TGENGIN_CHEMIQ_HOME). At 22 MB it fits in home, whereas $SCRATCH removes files unused for 90 days.
#
# **This is not isolation.** The official repository is public; a network-enabled solver can clone it. The path changes, not reachability.
#
# ## Use Sherlock modules rather than installing rdkit with pip
#
# This machine has glibc 2.17, incompatible with newer rdkit manylinux_2_28 wheels. The cluster provides `chemistry/py-rdkit/2024.3.2_py312` with python/3.12.1 and py-numpy/1.26.3_py312.
# The official verifier also needs `requests`, unavailable as a module. Create a `--system-site-packages` venv and install only that package. The official conda environment's pandas/matplotlib/openai/jupyterlab support model execution and plotting, not grading.
set -eu
cd "$(dirname "$0")"

REPO=https://github.com/oxpig/ChemIQ
PIN=63826f64990802e87f1b11b9192606a20838d522   # 2026-03-26 revision: 816 problems, after the 50 2D NMR replacements on 2025-07-10.
HOME_DIR="${TGENGIN_CHEMIQ_HOME:-$HOME/.cache/tgengin-chemiq}"
VENDOR="$HOME_DIR/vendor/ChemIQ"
VENV="$HOME_DIR/venv"
ENVSH="$HOME_DIR/env.sh"
ML_LINE="ml math devel chemistry python/3.12.1 py-numpy/1.26.3_py312 py-rdkit/2024.3.2_py312"

step () { echo; echo "── $* ──"; }
mkdir -p "$HOME_DIR"

if [ -z "${SLURM_JOB_ID:-}" ]; then
  echo "this looks like a login node (no SLURM_JOB_ID). run 'sdev' first." >&2
  exit 1
fi

step "0/4 Remove old copies remaining in the repository"
for stale in ChemIQ chemiq.jsonl vendor; do
  if [ -e "$stale" ]; then
    rm -rf "$stale"
    echo "Removed repository copy $stale: it was accessible to the solver"
  fi
done
echo "oracle exists only under $HOME_DIR"

step "1/4 Official repository (dataset + grader + OPSIN cache, pinned ${PIN:0:7})"
if [ -d "$VENDOR/.git" ]; then
  echo "Already have $(git -C "$VENDOR" rev-parse --short HEAD)"
else
  mkdir -p "$(dirname "$VENDOR")"
  git clone --depth 1 "$REPO" "$VENDOR"
fi
if [ "$(git -C "$VENDOR" rev-parse HEAD)" != "$PIN" ]; then
  git -C "$VENDOR" fetch --depth 1 origin "$PIN"
  git -C "$VENDOR" checkout -q "$PIN"
  echo "Pinned to $(git -C "$VENDOR" rev-parse --short HEAD)"
fi
echo "Dataset rows: $(wc -l < "$VENDOR/questions/chemiq.jsonl") rows"

step "2/4 Python: cluster module + venv containing only requests"
# `ml` is an Lmod shell function absent from noninteractive shells. Load Lmod's own initializer (LMOD_PKG=/share/software/user/open/lmod/lmod on Sherlock).
#
# shellcheck disable=SC1090
type ml >/dev/null 2>&1 || source "${LMOD_PKG:-/share/software/user/open/lmod/lmod}/init/bash"
ml purge
$ML_LINE
python3 -c 'import sys; assert sys.version_info[:2] == (3, 12), sys.version' \
  || { echo "python/3.12.1 did not load; see MEMORY.md note about ml in Claude's bash" >&2; exit 1; }
[ -x "$VENV/bin/python" ] || python3 -m venv --system-site-packages "$VENV"
PIP_CACHE_DIR="${SCRATCH:-/tmp}/.pip-cache" "$VENV/bin/pip" install -q "requests>=2.31"
"$VENV/bin/python" - <<'PY'
import numpy, requests, rdkit
from rdkit import Chem
print(f"numpy {numpy.__version__} | requests {requests.__version__} | rdkit {rdkit.__version__}")
assert Chem.MolToSmiles(Chem.MolFromSmiles("OCC")) == "CCO"
PY
# Source this when starting the grader, so module declarations have one authoritative location.
cat > "$ENVSH" <<EOF
# Generated by setup.sh. Start grading service: source $ENVSH && python stand.py
type ml >/dev/null 2>&1 || source "${LMOD_PKG:-/share/software/user/open/lmod/lmod}/init/bash"
ml purge
$ML_LINE
export TGENGIN_CHEMIQ_HOME="$HOME_DIR"
export PATH="$VENV/bin:\$PATH"
EOF
echo "Wrote $ENVSH"

step "3/4 OPSIN web service (required by the 200 smiles_to_iupac tasks)"
# Official code requests opsin.ch.cam.ac.uk, which redirects with 301 to www.ebi.ac.uk/opsin/ws; requests follows it.
# Measure one round trip here: official @timeout(2) includes network time, so more than 1.5 seconds is concerning.
t=$(curl -sL -m 15 -o /dev/null -w '%{time_total}' 'https://opsin.ch.cam.ac.uk/opsin/ethanol.json' || echo fail)
echo "ethanol → ${t}s"
case "$t" in fail) echo "OPSIN unreachable from this node - the 200 smiles_to_iupac questions will all grade as wrong" >&2 ;; esac

step "4/4 Self-test: official grader loading and correctness"
export TGENGIN_CHEMIQ_HOME="$HOME_DIR"
"$VENV/bin/python" stand.py --selftest

echo
echo "Ready. Start the grading service on an sdev node and forward its port to the engine:"
echo "  source $ENVSH && cd $(pwd) && python stand.py --level 1"
