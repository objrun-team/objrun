/** Full 87-task F coordinator entry. No standalone paid owner or provider key. */
import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { actualPin, verifyPin } from '../../../repair-2026-10-08/paid-resource-proof-v2.ts';
import { fullFRunId, acquireFullFAdmission, acquireFullFResource, type SharedFullFAdmission } from '../shared/shared-admission.ts';

const ROOT = resolve(import.meta.dir, '../../../..');
const HOME = join(ROOT, 'docs/repair-2026-10-10/full-f-rerun/skillsbench');
function read(path:string) {return JSON.parse(readFileSync(path, 'utf8'));}
function demand(ok:unknown, reason:string):asserts ok {if(!ok) throw Error(reason);}
export function inspectFullF() {
  const manifest=read(join(HOME,'manifest.json')), control=read(join(HOME,'../control.json'));
  demand(manifest.denominator===87 && manifest.plannedTaskRuns===87 && JSON.stringify(manifest.arms)==='["F"]', 'full_87_f_only_manifest_required');
  demand(manifest.taskSchedule.length===87 && new Set(manifest.taskSchedule.map((r:any)=>r.taskId)).size===87 && manifest.taskSchedule.every((r:any)=>r.arm==='F'), 'full_87_unique_f_schedule_required');
  demand(manifest.model==='deepseek/deepseek-v4.1-flash' && manifest.provider==='digitalocean' && manifest.allow_fallbacks===false && manifest.reasoning.effort==='high', 'frozen_model_provider_reasoning_changed');
  demand(control.allowedBenches.includes('skillsbench'), 'skillsbench_cancelled_by_coordinator');
  const readyPath=join(HOME,'runtime-readiness.json'), ready=existsSync(readyPath)?read(readyPath):undefined;
  return {manifest,control,ready,paidReady:control.paidReady===true,
    isolationReady:ready?.protocol==='skillsbench-full-f-task-gated-runtime-readiness-v2' && ready?.denominator===87 && Object.keys(ready?.taskReadiness??{}).length>0};
}

/** Called by the source-frozen full runtime only after actual isolation controls.
 * This is the sole admission hook for this Bench. It deliberately does not call
 * acquireOpenRouterAdmission or benchmarkFetch and never reads .env credentials.
 */
export async function connectSkillsBenchFullF(input:{output:string;sourcePins:ReturnType<typeof actualPin>[];runId?:string}) {
  const state=inspectFullF();
  demand(state.isolationReady, 'no_actual_task_private_grader_and_artifact_controls');
  demand(state.paidReady, 'shared_paid_adapter_not_ready');
  for(const p of state.manifest.sourceFilePins)verifyPin(p,undefined,2*1024**3);
  const runId=input.runId??fullFRunId(ROOT,'skillsbench');
  // Heavy lease comes first: a waiting Bench neither owns a paid lane nor holds
  // an unused cash reservation. A 409 queues at the caller/heartbeat level.
  const heavy=await acquireFullFResource(ROOT,'skillsbench','heavy-container');
  let admission:SharedFullFAdmission;
  try {admission=await acquireFullFAdmission({root:ROOT,output:input.output,runId,slug:'skillsbench',sourcePins:input.sourcePins});}
  catch(error){await heavy.release();throw error;}
  return {runId,admission,heavy,prices:admission.prices,balance:admission.balance,
    transport:(raw:string)=>admission.transport(raw),
    async close(result:{cashPin:ReturnType<typeof actualPin>;[key:string]:unknown}) {
      try {return await admission.finishLightweight(result);} finally {await heavy.release();}
    }};
}

if(import.meta.main) {
  const mode=process.argv[2]??'inspect';
  if(mode==='prepare') {
    const child=spawnSync('python',['-B',join(import.meta.dir,'prepare.py'),'--refresh'],{cwd:ROOT,windowsHide:true,stdio:'inherit'});
    process.exit(child.status??1);
  }
  const state=inspectFullF();
  if(mode==='inspect')console.log(JSON.stringify({phase:'preparing',denominator:87,arms:['F'],sharedPaidReady:state.paidReady,isolationReady:state.isolationReady,modelRequests:0}));
  else {
    demand(mode==='run','explicit_prepare_inspect_or_run_required');
    demand(state.isolationReady,'no_actual_task_private_grader_and_artifact_controls');
    demand(state.paidReady,'shared_paid_adapter_not_ready');
    // A runtime may only be loaded from this Bench's owned source directory,
    // with an actual ready proof generated by complete original grader controls.
    const workerPath=join(import.meta.dir,'runtime.ts');
    demand(existsSync(workerPath),'full_f_runtime_implementation_pending');
    const pin=state.ready.runtimeSourcePin;
    demand(resolve(pin.path)===workerPath,'foreign_or_old_pilot_runtime_denied');verifyPin(pin);
    const runtime=await import(workerPath);
    await runtime.runSkillsBenchFullF(state.manifest,connectSkillsBenchFullF);
  }
}
